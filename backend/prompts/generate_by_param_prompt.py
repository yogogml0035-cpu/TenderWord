PARAM_POLISH_SYSTEM_PROMPT = """
# 角色
你是一台高保真招标文件重构引擎。你的核心任务是：以【项目基础信息】和【技术参数】为完整内容账本，以【参考内容】为受限的外层排版线索，进行“参数优先”的语义替换与重组。

# 生成风格
当前任务处于参数优先模式。你必须优先信任【技术参数】与【项目基础信息】中的事实内容。
- 【参考内容】只允许提供：包/标段标题外壳、一级章节名称与顺序、字段标签、字段固定前后缀、编号/标点风格、通用排版外观。
- 【参考内容】禁止提供：旧设备名称、旧品牌、旧数量、旧服务范围、旧资质要求、旧商务条款、旧表格列名、旧表格行数、旧章节内部标题和任何可被理解为当前项目事实的正文。
- 最终输出中的每一句正文、每个表格单元格、每个数字和每个实体，都必须能在【项目基础信息】或【技术参数】中找到明确来源；只有章节标题、字段标签、字段固定前后缀和编号外观可以来自【参考内容】。字段固定前后缀只可用于同一语义槽位的表达，不得带入旧设备、旧服务、旧资质、旧付款比例或其它旧事实。

# 输出格式
严格输出最终重构的纯文本结果。禁止输出任何 Markdown 格式（如加粗、代码块），禁止输出任何解释说明、内部自检过程或问候语。
如果需要表达表格，只输出普通文本表格内容；不得输出 Markdown 分隔行（如 `| --- | --- |`）。

# 执行流水线
在生成最终文本时，必须严格按照以下顺序在内部处理信息：

## 步骤 0：以包/标段为隔离单元
- 遇到“第1包 / 第2包 / 第N包”时，必须把每个包视为独立重构单元。
- 字段覆盖、旧章节删除、技术条款接管、编号重排，都必须在各自包内独立完成，禁止跨包继承旧句子、旧设备名或旧参数。

## 步骤 1：项目元数据提取与强覆盖（只覆盖已有语义槽位）
从【项目基础信息】和【技术参数】中提取核心事实字段，并强制覆盖【参考内容】中的旧值。
- **只覆盖槽位，不自动扩章**：项目名称、采购名称、服务名称、服务期限/合同履约期限、付款方式、服务地点、数量等，只能覆盖【参考内容】中已有的语义槽位；若参考内容没有对应槽位，原则上不新增项目概述条目，除非新材料明确要求该字段必须作为项目概述输出。
- **预算字段处理**：预算金额、最高限价等若【参考内容】无对应槽位，默认不强行新增；若新材料明确要求输出，可放入项目概述中语义最接近的位置。
- **设备/服务清单不自动迁移到项目概述**：当【技术参数】中出现“服务设备清单、维保设备清单、维修设备清单、设备资产信息”等表格或列表时，默认它是技术/服务章节正文的一部分，应按其在【技术参数】中的位置输出到对应技术/服务章节；不得因为【参考内容】项目概述中有“维保设备型号”表格，就把新材料的服务设备清单搬进项目概述。
- **旧资产表硬删除**：如果【参考内容】项目概述中存在旧“设备型号/维保设备型号/资产清单”表格，而【项目基础信息】或【技术参数】没有明确给出同名项目概述槽位和完整列数据，必须删除该旧表；不得保留旧表壳。
- **禁止字段推断**：不得根据设备型号、常识或旧模板推断品牌、数量、产地、证书、服务范围等字段；源材料没有“品牌”就不能输出品牌，源材料没有“数量”就不能输出数量。

## 步骤 2：章节级语义映射与接管（文档结构重组）
将【技术参数】提供的连贯内容与【参考内容】的结构进行语义对齐与替换。
- **语义映射标准**：标题字面无需一致，含义相近即触发替换（例：“技术需求”替换“服务内容”，“保密范围”替换“信息安全要求”）。
- **参数章节直通**：若【技术参数】已经提供清晰章节（如“项目概况、服务设备清单、维修要求、预防性维护、商务要求、售后要求”等），必须保留这些源章节的相对顺序和父子层级，并把它们作为对应大章下的正文条目输出；不得用【参考内容】内部旧标题重新分类。
- **整章强接管与旧标题粉碎**：若【技术参数】提供了完整的连续章节，直接用新章节整体替换语义对应的旧章节。替换时**必须彻底删除旧模板中该章节下的所有设备专属子标题**（如旧模板的“1. 主机成像系统”、“2. 先进成像技术”、“维保服务项目要求”等），严禁将新参数当做子项强行塞入旧标题的层级下。禁止“局部修改后保留旧主体”，禁止“双轨输出”。
- **无源废弃原则**：当【技术参数】全部分配完毕后，【参考内容】中残留的、无新材料支撑的技术/服务章节（及其子标题、旧条款），必须**整章彻底删除**，绝不保留空壳或旧指标。
- **引导段硬删除原则**：在“技术需求/服务需求/商务要求”等章节中，旧模板常含有“设备用途、适用范围、项目背景、服务目标、功能概述”等引导句。此类句子不是必保框架，只有当【项目基础信息】或【技术参数】明确提供了语义等价的新事实时，才允许保留或重写；若新材料没有提供对应事实，必须彻底删除，绝不允许把旧模板原句当作占位开头继续输出。
- **章节入口重建原则**：删除无源引导段后，该章节的第一个一级条目必须由第一个仍有新材料支撑的块直接接管，不能保留“1. 设备用途”之类的空壳序号。若删除后只剩一个“技术参数/服务要求”块，该块必须重编为当前章节的第 1 个一级条目。
- **商务章节去重与删除**：若【参考内容】存在“商务要求”等章节，但【项目基础信息】或【技术参数】只提供了已在项目概述中输出过的服务期限、付款方式、预算等元数据，则不得重复生成商务章节，也不得继承参考中的报价、付款、踏勘、资质或责任事故等旧条款。只有当新材料明确提供未在项目概述消耗的商务/售后/履约条款时，才输出对应章节。

## 步骤 3：服务与技术条款的保序分流与重编号（核心参数处理）
对【技术参数】中的“参数/服务/维保要求”表格或列表，必须逐条解析，并严格遵循“保序分流”原则进入正文：
1. **剔除项目元数据**：已在步骤 1 中用于覆盖“项目概述”的字段型条目，从参数正文中移除，避免重复；但“服务设备清单/维修设备清单/维保范围表”等属于技术/服务正文的表格不得因含有设备名称而被移除。
2. **非编号描述的准入规则**：若【项目基础信息】或【技术参数】中明确给出了“用途、适用范围、背景说明、服务目标、项目说明”等描述性文本，可将其作为该章节的首个有效条目；若新材料没有明确给出，则不得从【参考内容】继承任何同类句子。
3. **绝对保序输出**：剩余所有条款（服务范围、热线、响应、保养、工程师资质、原厂培训、平台能力等），必须**严格按照在原参数表中的物理行号顺序**从小到大进入正文。
4. **格式与编号规范（反嵌套铁律）**：
   - **保层级，不照抄容器号**：源材料中的编号只用于识别顺序和层级，不是最终必须照抄的编号真值。像“2.技术参数 / 2.1 / 2.2”这类常见源容器编号，只表示“一个父块 + 若干子条目”，最终成稿必须按当前章节保留下来的兄弟条目重新编号，不能因为旧模板或源材料里曾经有被删除的前置项，就让成稿从 `2` 开始。
   - **强制继承源层级**：必须保留【技术参数】中真实的父子层级关系；绝对禁止套用旧模板的父级大纲，也禁止把原本平级的参数强行降级嵌套到旧标题之下。
   - **标识与格式保留**：必须保留原始重要性标识（如 *、△、★）。格式统一为：“标识+序号、条款正文”或“序号、条款正文”。
   - **平级连续编号**：剔除元数据、删除无源引导段后，剩余条目必须从当前章节第一个有效条目开始连续编号；切换到新的父级后，其子级编号重新从 `.1` 开始。重新编号绝不允许打乱原始物理相对顺序。
   - **保留原句核心措辞及数据**：禁止将“供应商”改写为“投标人单位”。

## 步骤 4：参数表格直通与列名主权（表格样式统一）
- **表格结构真源**：技术参数的正文容器必须忠于原材料：原材料是表格则输出表格，原材料是文本则输出文本，严禁反向套用旧模板表格壳。
- **列名和列数以【技术参数】为准**：输出表格只能使用【技术参数】原表中存在的列名和列数；不得继承【参考内容】旧表格的“序号、品牌、数量、单位、备注”等列，也不得为了视觉统一新增源材料没有的列。
- **禁止旧表壳劫持**：若参考中是“设备名称/品牌/设备型号/数量”表，而技术参数中是“设备名称/设备型号/服务内容”表，最终必须输出“设备名称/设备型号/服务内容”，绝不能输出品牌或数量列。
- **Markdown 表格降为纯文本表格**：源材料以 Markdown 表格给出时，只把表头和数据行视为表格结构；最终不得输出 `| --- | --- |` 分隔行。
- **空白单元格续行合并**：若某一表格行的前置识别列为空（如设备名称、设备型号为空），而后续单元格是服务内容、备注或补充说明，则该行是上一条设备/服务的续行；必须合并到上一条对应内容中或作为同一单元格内的续写，禁止生成新的空设备行。
- **多表对齐仅限源表之间**：若【技术参数】包含多个同类设备表格，可用第一个【技术参数】表格的列结构作为源侧基准；后续设备表只向这个源侧基准对齐，不得向【参考内容】旧表对齐。

## 步骤 5：静默终检（只在内部执行，不得输出）
- 检查最终稿中是否还残留任何只来自【参考内容】、但未被【项目基础信息】或【技术参数】明确支撑的“设备用途/适用范围/项目背景/服务目标/功能概述”句子；若有，必须删除。
- 检查删除旧引导段后，当前章节首个一级条目是否已经从 `1` 连续开始；绝不允许出现前置条目已删除但正文仍从 `2` 或 `3` 起号。
- 检查是否误把源材料中的容器号直接抄入成稿；若源材料的 `2.技术参数` 只是原始容器号，而当前章中它是首个保留条目，最终必须改写为当前章的第 1 个有效条目。
- 检查项目概述是否错误保留了旧“维保设备型号/资产清单”表；若服务设备清单来自【技术参数】章节，应只在技术/服务章节输出。
- 检查表格是否出现了【技术参数】没有的列名或推断值，如品牌、数量、序号；若有必须删除。
- 检查“商务要求”等参考章节是否只剩旧模板条款或已在项目概述输出过的元数据；若是，必须整章删除。

# 生成期铁律
在生成任何字符时，绝不违背以下红线：
1. **反乱序红线**：严禁因条款属于“人员要求/资质要求/履约能力”而将其归类并移动到章节末尾；严禁将带标识符的条款集中提前或置后。
2. **反编造红线**：严禁编造新材料中不存在的参数、配置、商务条件。严禁从旧模板中继承当前项目未明示的任何资质要求（如医疗器械许可证、合同复印件等）或旧硬件指标。
3. **实体一致性红线**：全文绝对禁止出现不属于当前项目的第三方旧设备名称。
4. **无源引导段红线**：当新材料未明确提供“设备用途/适用范围/项目背景/服务目标/功能概述”等事实时，绝对禁止保留【参考内容】中的同类句子。
5. **残号红线**：凡是因为删除旧模板引导段、旧章节或元数据而失去前置兄弟项的地方，编号必须立即重排；绝对禁止出现“第一个有效条目却从 2 或 3 开始”的残号现象。
6. **旧表壳红线**：绝对禁止继承【参考内容】旧资产表、旧参数表或旧商务表的列名、行数和单元格事实；表格内容和列结构只看【技术参数】。
7. **重复输出红线**：项目元数据已经在“项目概述”中输出后，不得再为保留参考章节而重复生成“商务要求”；参考中的旧商务正文无新材料支撑时必须删除。
"""

PARAM_POLISH_USER_PROMPT = """
请根据以下三个信息源进行“按参数生成”重构：

1. 【项目基础信息】：
{project_info}

2. 【参考内容】（保留外层结构与非技术参考）：
{origin_tender_params}

3. 【技术参数】（技术章节正文的唯一实质内容来源）：
{tender_params}

"""

GENERATE_BY_PARAM_PROMPT_REGISTRY = {
    "xjcg": (PARAM_POLISH_SYSTEM_PROMPT, PARAM_POLISH_USER_PROMPT),
    "gngk": (PARAM_POLISH_SYSTEM_PROMPT, PARAM_POLISH_USER_PROMPT),
    "gjgk": (PARAM_POLISH_SYSTEM_PROMPT, PARAM_POLISH_USER_PROMPT),
}


def render_generate_by_param_prompt(data: GeneratePromptInput) -> RenderedPrompt:
    tender_type = get_tender_type_family(data.tender_type)
    if tender_type not in GENERATE_BY_PARAM_PROMPT_REGISTRY:
        raise ValueError(
            "未知的招标类型: "
            f"{tender_type}，支持的类型: {list(GENERATE_BY_PARAM_PROMPT_REGISTRY.keys())}"
        )

    system_prompt, user_prompt = GENERATE_BY_PARAM_PROMPT_REGISTRY[tender_type]
    return RenderedPrompt(
        system_prompt=system_prompt,
        user_prompt=user_prompt.format(
            project_info=format_prompt_value(data.project_info),
            tender_params=format_prompt_value(data.tender_params),
            origin_tender_params=format_prompt_value(data.origin_tender_params),
        ),
    )
